function wiringHint(match: HarnessMatch | null): string[] {
  const label = match?.label ?? '';
  if (label.includes('BullMQ')) {
    return [
      'BullMQ wiring: in the Worker processor call reportRunEvent with status running at',
      "start; on worker 'completed' send succeeded with the result as outcome; on 'failed'",
      'send failed (or timed_out) with the error. Use `${job.id}:<transition>` as eventId.',
    ];
  }
  if (label.includes('DBOS')) {
    return [
      'DBOS wiring: report from a DBOS step after each run write, so a retry resends the same',
      'eventId. Send running when the workflow starts and succeeded or failed when it ends.',
    ];
  }
  if (label.includes('Temporal')) {
    return [
      'Temporal wiring: report from an activity at workflow start and end. Temporal retries',
      'activities, so keep eventId stable per transition.',
    ];
  }
  if (label.includes('Inngest')) {
    return [
      'Inngest wiring: report inside step.run blocks at start and end of the function so',
      'retries reuse the step result.',
    ];
  }
  if (label.includes('pg-boss')) {
    return ['pg-boss wiring: report at the start and end of the work handler.'];
  }
  if (match?.shape === 'http-runner') {
    return [
      'HTTP wiring: enqueue calls your task endpoint; report running when the handler',
      'accepts the job and a terminal status when it finishes.',
    ];
  }
  return ['Report running when a job starts and a terminal status when it ends.'];
}
