#!/usr/bin/env node
// Copies docker/.env.example into the platform bundle so the workspace export zip can include it.
// The standalone Docker image does not ship docker/, so the template is embedded as a module.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const template = readFileSync(join(root, 'docker/.env.example'), 'utf8');
const out = join(root, 'apps/platform/src/lib/workspace-transfer/env-example.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/sync-docker-env-example.mjs from docker/.env.example. Do not edit.\nexport const DOCKER_ENV_EXAMPLE = ${JSON.stringify(template)};\n`,
);
console.log(`Wrote ${out}`);
